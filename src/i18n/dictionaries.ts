export const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, id };

export function translate(lang: Language, key: TranslationKey, vars?: Record<string, string | number>): string {
  let text: string = dictionaries[lang]?.[key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return text;
}
